LOCALES = ["en", "zh_CN", "zh_TW", "ja", "ko", "es", "fr", "de", "ru", "pt_BR"]

def main():
    os.makedirs(LOCALES_DIR, exist_ok=True)
    for loc in LOCALES:
        loc_dir = os.path.join(LOCALES_DIR, loc)
        os.makedirs(loc_dir, exist_ok=True)
        out = {}
        for key, trans in MESSAGES.items():
            text = trans.get(loc, trans.get("en", ""))
            out[key] = {
                "message": text,
                "description": f"Translation for {key}"
            }
        filepath = os.path.join(loc_dir, "messages.json")
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        print(f"Generated {loc}/messages.json with {len(out)} keys")

if __name__ == "__main__":
    main()
